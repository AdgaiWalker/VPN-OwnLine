def hint_from_log(lines):
    txt = "\n".join(lines or []).lower()
    # 预检的中文原因自己就够清楚，原样带出来
    m = re.search(r"预检未通过：(.+)", "\n".join(lines or []))
    if m:
        return "预检没通过：%s\n请更换符合条件的空白 Ubuntu 22.04+ / Debian 12+ 服务器后重试。" % m.group(1).strip()
    for key, text in RULES:
        if key in txt:
            return text
    return DEFAULT
